# -*- coding: utf-8 -*-
"""
==============================================================
  НАСТРОЙКИ STEALTH TYPER  —  единственный файл, который нужно править
==============================================================

Как это работает:
  1. Ниже — общие настройки (по умолчанию для всех сайтов).
  2. В разделе SITES можно описать профили конкретных сайтов: в профиле
     указывается только то, что отличается от общих настроек.
  3. ACTIVE_SITE — какой профиль использовать. Можно не менять файл, а
     выбирать профиль при запуске:  python app/stealth_typer.py --site мой_сайт

Любую настройку можно временно переопределить из командной строки,
см. README.md (--text, --mode, --cursor, --wpm, --dry-run, --list).
"""

# ==============================================================
# 1. БРАУЗЕР
# ==============================================================

# "launch" — скрипт сам открывает НОВОЕ окно Edge (с сохраняемым профилем).
# "attach" — скрипт подключается к УЖЕ ОТКРЫТОМУ окну Edge.
#            Для этого Edge должен быть запущен с отладочным портом:
#            просто запустите start_edge_debug.bat (или включите AUTO_START_EDGE).
BROWSER_MODE = "launch"

BROWSER_CHANNEL = "msedge"          # "msedge" / "chrome" / "chromium"
USER_DATA_DIR = "data/edge_user_data"    # профиль для режима launch (путь от корня проекта)

# --- только для BROWSER_MODE = "attach" ---
DEBUG_PORT = 9222                   # порт отладки Edge
AUTO_START_EDGE = True              # True: если Edge с портом не найден — запустить его самим
                                    #       (отдельный профиль data/edge_debug_profile, не ваш основной)
ATTACH_TAB = ""                     # часть адреса или заголовка нужной вкладки.
                                    # Пусто: берётся видимая вкладка, а если их несколько — спросит.
ATTACH_GOTO = False                 # True: в режиме attach тоже перейти на TARGET_URL

# ==============================================================
# 2. СТРАНИЦА И ПОЛЕ
# ==============================================================

TARGET_URL = ""                     # адрес страницы. Пусто — не переходить
                                    # (откроете нужную страницу сами).
PAGE_LOAD_TIMEOUT_MS = 30_000
FIELD_WAIT_TIMEOUT_MS = 15_000      # сколько ждать появления поля
CONFIRM_BEFORE_START = True         # True: перед вводом спросить «страница готова? Enter».
                                    # Нужно для входа в аккаунт, капчи, выбора вкладки и т.п.

# Куда ставить курсор:
#   "auto"   — скрипт сам выбирает редактор/поле и ставит курсор (см. ниже)
#   "manual" — ВЫ сами кликаете в нужное место в редакторе, возвращаетесь
#              в консоль, жмёте Enter — скрипт печатает с того места, где курсор.
CURSOR_MODE = "auto"

# Только для CURSOR_MODE = "auto":
FIELD_SELECTOR = ""                 # CSS-селектор поля. Пусто — для Monaco берётся редактор
                                    # по номеру FIELD_INDEX (видимые редакторы, сверху вниз).
                                    # Список редакторов на странице:  python app/stealth_typer.py --list
FIELD_INDEX = 0                     # номер редактора/совпадения (с нуля)
CURSOR_LINE = "end"                 # "end" — конец документа, "start" — начало, или номер строки (1, 2, ...)
CURSOR_COLUMN = "end"               # "end" — конец строки, или номер колонки (1, 2, ...)

# ==============================================================
# 3. ТЕКСТ
# ==============================================================

TEXT_FILE = "input_text.txt"      # файл с текстом (UTF-8). Отступы сохраняются как есть.
TEXT_INLINE = ""                    # запасной текст, если файла нет
TRIM_TRAILING_NEWLINES = True       # убрать пустые строки в самом конце файла

# ==============================================================
# 4. СКОРОСТЬ И «ЧЕЛОВЕЧНОСТЬ»
# ==============================================================

# Скорость печати, слов в минуту (1 слово = 5 знаков).
# Скорость НЕ постоянная: она плавно гуляет между WPM_MIN и WPM_MAX.
WPM_MIN = 40
WPM_MAX = 90

VARIABILITY = 0.5       # 0..1  как сильно и часто скорость «гуляет» (0 — почти ровно)
FATIGUE = 0.5           # 0..1  насколько скорость падает от усталости (0 — усталости нет)
FATIGUE_MINUTES = 6.0   # за сколько минут непрерывной печати усталость наберётся примерно на 2/3
PAUSES = 1.0            # множитель пауз «подумать» (0 — без пауз, 2 — вдвое больше)
INDENT_FAST = True      # отступы в начале строк печатаются быстро (как будто держат пробел/Tab)

KEY_HOLD_MS = (45, 110) # сколько мс удерживается клавиша (от, до)

ERROR_RATE = 0.02       # вероятность опечатки на букву (0 — без опечаток). Все опечатки исправляются.
SWAP_SHARE = 0.25       # доля опечаток-«перестановок» двух соседних букв
DOUBLE_SHARE = 0.15     # доля опечаток-«двойное нажатие»; остальное — соседняя клавиша
TYPO_NOTICE_MAX = 3     # через сколько знаков человек «замечает» опечатку (0..N)

START_DELAY_S = 3       # пауза перед началом ввода (секунды), чтобы успеть переключить окно

# ==============================================================
# 5. MONACO / РЕДАКТОРЫ КОДА
# ==============================================================

# Как вести себя с «помощью» редактора:
#   "natural" — помощь редактора ОСТАВЛЕНА, скрипт работает вместе с ней, как человек:
#                 * кавычки и скобки: печатает внутри, а закрывающий знак «проходит» через уже стоящий;
#                 * Enter: принимает отступ, который поставил редактор, и подгоняет его под ваш текст
#                   (лишнее стирает Backspace, недостающее допечатывает);
#                 * Enter между тегами или скобками (редактор делает пустую строку): второй Enter не нажимает,
#                   а уходит из пустой строки вниз к закрывающему тегу/скобке;
#   "literal" — помощь редактора ОТКЛЮЧЕНА (автоотступы, автозакрытие скобок и кавычек), всё печатается
#                 буквально. Запасной вариант: надёжнее, но менее «похоже на человека».
# Подсказки и автодополнение (они ломают Enter) отключаются в любом режиме, пока MONACO_DISABLE_AUTOFEATURES = True.
MONACO_MODE = "natural"
MONACO_DISABLE_AUTOFEATURES = True
MONACO_RESTORE_OPTIONS = True       # после ввода вернуть настройки редактора как были
# Что делать, когда сайт сам вставил закрывающий тег (</div> после <div>):
#   "skip"   — печатать ВНУТРИ тега, а дойдя до закрывающего тега в тексте — просто перепрыгнуть через него
#              (End / стрелка вправо). Быстрее и выглядит естественнее, как у человека с автозакрытием.
#              Так же обрабатываются скобки и кавычки, вставленные редактором.
#   "delete" — сразу удалять всё, что редактор/сайт вставил справа от курсора (клавишей Delete),
#              и печатать закрывающие знаки руками. Запасной вариант, если "skip" даёт расхождения.
AUTOCLOSE_MODE = "skip"
AUTOCLOSE_WAIT_MS = 300             # сколько ждать, пока сайт вставит закрывающий тег после «>»
                                    # (0 — не ждать)

# ==============================================================
# 6. ПОВЕДЕНИЕ
# ==============================================================

KEEP_BROWSER_OPEN = True            # launch: оставить окно открытым после ввода
VERIFY_RESULT = True                # сверить текст в редакторе с исходным после ввода
SCREENSHOT_ON_ERROR = True
LOG_FILE = "data/stealth_typer.log"    # пусто — не писать лог в файл
RANDOM_SEED = None                  # число — повторяемый «почерк» (для отладки); None — случайно

# ==============================================================
# 7. ПРОФИЛИ САЙТОВ
# ==============================================================
# Укажите только то, что отличается от общих настроек выше.
# Названия настроек — те же, что выше (заглавными буквами).
# ВАЖНО: называйте профили ЛАТИНИЦЕЙ без пробелов (my_site, shop_1). Русские названия ломаются,
# если скрипт запускается из .bat-файла или через os.system: Windows портит кодировку (см. README, раздел 11).

ACTIVE_SITE = ""                    # пусто — только общие настройки

SITES = {
    # Пример: Monaco, второй видимый редактор, печатать в конец, подключаясь к открытому Edge
    "example_monaco": {
        "BROWSER_MODE": "attach",
        "FIELD_INDEX": 1,
        "CURSOR_LINE": "end",
    },
    # Пример: свой курсор, текст из другого файла
    "example_manual_cursor": {
        "CURSOR_MODE": "manual",
        "TEXT_FILE": "texts/page2.html",
        "WPM_MIN": 60,
        "WPM_MAX": 110,
    },
}
